#!/usr/bin/env python3
"""Archive genuine NISAR ZORI results as LOCAL, static before/after examples.

Run ONCE in Google Cloud Shell after "git pull"; the deployed Cloud Run API
already holds private NASA credentials. No Earthdata login/token is needed here.

This uses only the production ZORI /analyze, /status, and /image APIs, never
NASA article illustrations. A case is registered only when its scientific
output and actual PNG bytes pass validation. GCOV produces before/after/change;
GUNW produces *two authentic grids*: phase and measured coherence, not faked before/after.

Example:
  python3 tools/precompute_cases.py
  python3 tools/precompute_cases.py --only mozambique

Afterward deploy the Cloud Shell directory with "gcloud run deploy --source ."
and commit+push the generated assets to preserve them in the GitHub source.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "frontend" / "assets" / "cases"
MANIFEST = ASSETS / "manifest.json"
CASE_JS = ROOT / "frontend" / "case-data.js"
DEFAULT_URL = "https://zori-observatory-462951352323.europe-west6.run.app"

CASES = {
    "mozambique": {
        "lat": -24.5, "lon": 33.2, "start_date": "2025-12-25",
        "end_date": "2026-02-01", "change": "flood",
        "mode": "gcov_backscatter_difference",
        "image_kinds": ("before", "after", "difference"),
    },
    "maize": {
        "lat": -28.5, "lon": 27.0, "start_date": "2025-11-22",
        "end_date": "2026-03-10", "change": "forest",
        "mode": "gcov_backscatter_difference",
        "image_kinds": ("before", "after", "difference"),
    },
    "venezuela": {
        "lat": 10.55, "lon": -66.9, "start_date": "2026-06-17",
        "end_date": "2026-07-08", "change": "ground",
        "mode": "gunw_unwrapped_phase",
        "image_kinds": ("difference", "coherence"),
    },
}
PNG_HEADER = b"\x89PNG\r\n\x1a\n"


def request_bytes(url: str, payload: dict | None = None, timeout: int = 70) -> bytes:
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    req = urllib.request.Request(
        url, data=body,
        headers={"Accept": "application/json" if payload is not None else "*/*",
                 **({"Content-Type": "application/json"} if body else {})},
        method="POST" if body is not None else "GET",
    )
    with urllib.request.urlopen(req, timeout=timeout) as response:
        return response.read()


def request_json(url: str, payload: dict | None = None) -> dict:
    return json.loads(request_bytes(url, payload).decode("utf-8"))


def save_manifest(data: dict) -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    content = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True)
    MANIFEST.write_text(content + "\n", encoding="utf-8")
    # Only local, case-specific, provenance-checked paths are inserted.
    js = (
        "/* Authentic cached NISAR quicklooks, generated by tools/precompute_cases.py. */\n"
        "window.ZORI_CASE_DATA = " + content + ";\n"
        "for (const sample of SAMPLES) {\n"
        "  const record = window.ZORI_CASE_DATA[sample.id];\n"
        "  if (record) Object.assign(sample, record);\n"
        "}\n"
    )
    CASE_JS.write_text(js, encoding="utf-8")


def archive_case(base: str, name: str, spec: dict, max_wait: int) -> dict:
    payload = {k: spec[k] for k in ("lat", "lon", "start_date", "end_date", "change")}
    print(f"[{name}] Starting authentic {spec['change']} analysis through ZORI Cloud Run", flush=True)
    job = request_json(base + "/analyze", payload)
    job_id = job.get("job_id")
    if not job_id:
        raise RuntimeError("Cloud Run did not return a job ID: " + str(job)[:250])
    started = time.monotonic()
    last_status = None
    last_report = -100.0
    while time.monotonic() - started < max_wait:
        info = request_json(base + "/status/" + urllib.parse.quote(str(job_id), safe=""))
        status = info.get("status")
        elapsed = time.monotonic() - started
        if status != last_status or elapsed - last_report > 30:
            print(f"[{name}] {status} · {int(elapsed)}s elapsed", flush=True)
            last_status = status
            last_report = elapsed
        if status == "error":
            raise RuntimeError("NISAR processing failed: " + str(info.get("error"))[:450])
        if status == "done":
            break
        if status not in ("processing", "queued"):
            raise RuntimeError("Unexpected job state: " + str(status))
        time.sleep(5)
    else:
        raise TimeoutError(f"ZORI science job exceeded {max_wait} seconds")

    stats = info.get("stats") or {}
    if stats.get("mode") != spec["mode"]:
        raise ValueError("Unexpected science mode: " + str(stats.get("mode")))
    sources = info.get("sources") or []
    if spec["mode"] == "gcov_backscatter_difference":
        if len(sources) != 2 or stats.get("valid_pixels", 0) < 250:
            raise ValueError("GCOV output lacks a validated pair of scientific input scenes")
        if sources[0].get("maturity") != sources[1].get("maturity"):
            raise ValueError("Mixed-maturity NISAR scenes cannot be compared")
    elif len(sources) != 1 or stats.get("coherent_pixels", 0) < 120:
        raise ValueError("GUNW output lacks a valid interferometric phase result")

    image_urls = info.get("images") or {}
    downloads = {}
    for kind in spec["image_kinds"]:
        path = image_urls.get(kind)
        if not isinstance(path, str) or not path.startswith("/image/"):
            raise ValueError(f"Missing authentic {kind} quicklook")
        png = request_bytes(urllib.parse.urljoin(base + "/", path.lstrip("/")))
        if not png.startswith(PNG_HEADER) or len(png) < 512:
            raise ValueError(f"Invalid or empty {kind} radar PNG; archive unchanged")
        downloads[kind] = png

    # Write the images *only after every required download validates*.
    record = {
        "stats": stats,
        "sources": sources,
        "method": info.get("method", ""),
        "processedAt": datetime.now(timezone.utc).isoformat(),
        "precomputed": True,
    }
    for kind, png in downloads.items():
        filename = f"{name}-{kind}.png"
        path = ASSETS / filename
        path.write_bytes(png)
        key = "image" if (name == "venezuela" and kind == "difference") else kind
        record[key] = "/assets/cases/" + filename
    print(
        f"[{name}] Archived {len(downloads)} authentic PNGs, "
        f"{len(sources)} NISAR science granule(s), {stats['mode']}", flush=True
    )
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default=DEFAULT_URL, help="Public ZORI service URL")
    parser.add_argument("--only", default="mozambique,maize,venezuela",
                        help="Comma-separated names: mozambique,maize,venezuela")
    parser.add_argument("--max-wait", type=int, default=1100,
                        help="Seconds to wait for each Cloud Run scientific processing job")
    args = parser.parse_args()
    names = [x.strip().lower() for x in args.only.split(",") if x.strip()]
    if not names or any(n not in CASES for n in names):
        parser.error("Choose one or more names: " + ", ".join(CASES))
    base = args.url.rstrip("/")
    ASSETS.mkdir(parents=True, exist_ok=True)
    existing = json.loads(MANIFEST.read_text(encoding="utf8")) if MANIFEST.exists() else {}
    if not isinstance(existing, dict):
        raise ValueError("Case manifest must be a JSON object")

    successes, failures = [], []
    for name in names:
        try:
            result = archive_case(base, name, CASES[name], args.max_wait)
            existing[name] = result
            save_manifest(existing)
            successes.append(name)
        except (urllib.error.URLError, ValueError, TimeoutError, RuntimeError, KeyError) as exc:
            failures.append(name)
            print(f"[{name}] NOT ARCHIVED: {str(exc)[:500]}", file=sys.stderr, flush=True)

    print("\n=== ZORI PRECOMPUTED CASES ===", flush=True)
    print("READY:", ", ".join(successes) or "none", flush=True)
    print("NOT READY:", ", ".join(failures) or "none", flush=True)
    print("Manifest:", MANIFEST, flush=True)
    print("No NASA illustrations or unverified data were downloaded.", flush=True)
    if successes:
        print("Next: deploy the current Cloud Shell directory to Cloud Run.", flush=True)
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
